"""Durable adversarial-assurance store over DurableCoordinationStore.

Canonical package for AAE persistence (AAE-034–AAE-038):

* immutable assurance artifacts (AAE-034)
* campaign state, receipts, gaps, and histories (AAE-035)
* campaign Merkle roots, seal manifests, and benchmarks (AAE-036)
* policy revision and promotion CAS (AAE-037)
* crash recovery, idempotent replay, and concurrency fencing (AAE-038)

This package is the sole kit package-export owner after AAE-034 through
AAE-037 exist.  It re-exports closed public contracts and durable
implementations without redefining identity, receipt, signature, CAS, or
storage authorities.  Import has no side effects and never mutates production
policy.
"""

